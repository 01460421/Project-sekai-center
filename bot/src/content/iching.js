/* 由六爻字串查卦（初爻在左） */
export const hexByLines = lines => HEXAGRAMS.find(h => h.lines === lines);

/* 畫爻：由上而下顯示 */
export function drawLines(lines, changing = []) {
  const out = [];
  for (let i = 5; i >= 0; i--) {
    const yang = lines[i] === '1';
    const mark = changing.includes(i) ? (yang ? ' ○' : ' ×') : '';
    out.push((yang ? '━━━━━━' : '━━  ━━') + mark);
  }
  return out.join('\n');
}
